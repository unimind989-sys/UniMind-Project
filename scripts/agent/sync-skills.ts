import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { parse } from "yaml";

export const skillSourceRoot = ".agents/skills";
export const claudeSkillRoot = ".claude/skills";

export type SkillSource = Readonly<{
  name: string;
  markdown: string;
  manual: boolean;
  entries: readonly string[];
}>;

export type SkillDrift = Readonly<{
  name: string;
  kind: "drifted" | "missing" | "extra";
}>;

const normalize = (text: string) => text.replace(/\r\n/g, "\n");

function isManual(openAiYaml: string | undefined): boolean {
  if (openAiYaml === undefined) return false;
  const parsed: unknown = parse(openAiYaml);
  if (typeof parsed !== "object" || parsed === null) return false;
  const policy: unknown = (parsed as Record<string, unknown>)["policy"];
  if (typeof policy !== "object" || policy === null) return false;
  return (
    (policy as Record<string, unknown>)["allow_implicit_invocation"] === false
  );
}

export async function listSkillSources(
  repoRoot: string,
): Promise<SkillSource[]> {
  const root = path.join(repoRoot, skillSourceRoot);
  const dirs = (await readdir(root, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const sources: SkillSource[] = [];
  for (const name of dirs) {
    const dir = path.join(root, name);
    const skillPath = path.join(dir, "SKILL.md");
    if (!existsSync(skillPath)) continue;
    const yamlPath = path.join(dir, "agents", "openai.yaml");
    const yaml = existsSync(yamlPath)
      ? await readFile(yamlPath, "utf8")
      : undefined;
    sources.push({
      name,
      markdown: normalize(await readFile(skillPath, "utf8")),
      manual: isManual(yaml),
      entries: (await readdir(dir)).sort(),
    });
  }
  return sources;
}

function splitFrontmatter(markdown: string): [string, string] {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(markdown);
  if (match === null || match[1] === undefined) {
    throw new Error("SKILL.md must start with YAML frontmatter.");
  }
  return [match[1], markdown.slice(match[0].length)];
}

function isRelativeTarget(target: string): boolean {
  return !/^([a-z][a-z0-9+.-]*:|#|\/)/i.test(target);
}

function rewriteLine(
  line: string,
  source: SkillSource,
  sourceDir: string,
): string {
  const linked = line.replace(/\]\(([^)\s]+)\)/g, (whole, target: string) => {
    if (!isRelativeTarget(target)) return whole;
    const resolved = path.posix.normalize(path.posix.join(sourceDir, target));
    return `](../../../${resolved})`;
  });
  return linked.replace(/`([^`\s]+)`/g, (whole, code: string) => {
    const first = code.split("/")[0] ?? "";
    const pathLike = code.includes("/") || first.includes(".");
    if (!pathLike || !source.entries.includes(first)) return whole;
    return `\`${sourceDir}/${code}\``;
  });
}

export function rewriteSkillBody(body: string, source: SkillSource): string {
  const sourceDir = `${skillSourceRoot}/${source.name}`;
  let inFence = false;
  return body
    .replaceAll("${CLAUDE_SKILL_DIR}", sourceDir)
    .split("\n")
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) inFence = !inFence;
      return inFence ? line : rewriteLine(line, source, sourceDir);
    })
    .join("\n");
}

export function renderClaudeSkill(source: SkillSource): string {
  const [frontmatter, body] = splitFrontmatter(source.markdown);
  const header =
    source.manual && !/^disable-model-invocation:/m.test(frontmatter)
      ? `${frontmatter}\ndisable-model-invocation: true`
      : frontmatter;
  const sourceDir = `${skillSourceRoot}/${source.name}`;
  return [
    `---\n${header}\n---`,
    `<!-- Generated by pnpm skills:sync from ${sourceDir}/SKILL.md. Do not edit. -->`,
    "",
    `Supporting files for this skill live in \`${sourceDir}/\`.`,
    "",
    rewriteSkillBody(body, source).replace(/^\n+/, ""),
  ].join("\n");
}

async function listGenerated(repoRoot: string): Promise<string[]> {
  const root = path.join(repoRoot, claudeSkillRoot);
  if (!existsSync(root)) return [];
  return (await readdir(root, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name);
}

export async function findSkillDrift(repoRoot: string): Promise<SkillDrift[]> {
  const sources = await listSkillSources(repoRoot);
  const names = new Set(sources.map((source) => source.name));
  const drift: SkillDrift[] = [];
  for (const source of sources) {
    const dir = path.join(repoRoot, claudeSkillRoot, source.name);
    const target = path.join(dir, "SKILL.md");
    if (!existsSync(target)) {
      drift.push({ name: source.name, kind: "missing" });
      continue;
    }
    const actual = normalize(await readFile(target, "utf8"));
    const files = await readdir(dir);
    if (actual !== renderClaudeSkill(source) || files.length !== 1) {
      drift.push({ name: source.name, kind: "drifted" });
    }
  }
  for (const name of await listGenerated(repoRoot)) {
    if (!names.has(name)) drift.push({ name, kind: "extra" });
  }
  return drift;
}

export async function syncSkills(repoRoot: string): Promise<void> {
  const sources = await listSkillSources(repoRoot);
  const names = new Set(sources.map((source) => source.name));
  for (const source of sources) {
    const dir = path.join(repoRoot, claudeSkillRoot, source.name);
    await rm(dir, { recursive: true, force: true });
    await mkdir(dir, { recursive: true });
    await writeFile(path.join(dir, "SKILL.md"), renderClaudeSkill(source));
  }
  for (const name of await listGenerated(repoRoot)) {
    if (names.has(name)) continue;
    await rm(path.join(repoRoot, claudeSkillRoot, name), {
      recursive: true,
      force: true,
    });
  }
}

async function main(): Promise<void> {
  const repoRoot = process.cwd();
  if (process.argv.includes("--check")) {
    const drift = await findSkillDrift(repoRoot);
    for (const item of drift) {
      console.error(`${claudeSkillRoot}/${item.name}: ${item.kind}`);
    }
    if (drift.length > 0) {
      console.error("Run `pnpm skills:sync` to regenerate Claude skills.");
      process.exitCode = 1;
    } else {
      console.log("Claude skill copies match their sources.");
    }
    return;
  }
  await syncSkills(repoRoot);
  console.log(`Synced Claude skills into ${claudeSkillRoot}.`);
}

const entry = process.argv[1];
